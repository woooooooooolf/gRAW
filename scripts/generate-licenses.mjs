import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entries = new Map();

const cargo = JSON.parse(
  execFileSync(
    "cargo",
    [
      "metadata",
      "--format-version",
      "1",
      "--filter-platform",
      "x86_64-pc-windows-msvc",
      "--manifest-path",
      join(root, "src-tauri", "Cargo.toml"),
    ],
    { encoding: "utf8", cwd: root, maxBuffer: 64 * 1024 * 1024 },
  ),
);

for (const pkg of cargo.packages) {
  if (!pkg.source) continue;
  const key = `cargo:${pkg.name}@${pkg.version}`;
  entries.set(key, {
    ecosystem: "Cargo",
    name: pkg.name,
    version: pkg.version,
    license: pkg.license || "UNKNOWN",
    homepage: pkg.homepage || pkg.repository || "",
  });
}

const visited = new Set();
function scanNodeModules(directory) {
  if (!existsSync(directory)) return;
  const real = resolve(directory);
  if (visited.has(real)) return;
  visited.add(real);
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith(".")) continue;
    const path = join(directory, entry.name);
    if (entry.name.startsWith("@")) {
      for (const scoped of readdirSync(path, { withFileTypes: true })) {
        if (scoped.isDirectory()) scanPackage(join(path, scoped.name));
      }
    } else {
      scanPackage(path);
    }
  }
}

function scanPackage(directory) {
  const manifest = join(directory, "package.json");
  if (!existsSync(manifest)) return;
  try {
    const pkg = JSON.parse(readFileSync(manifest, "utf8"));
    if (pkg.name && pkg.version && pkg.name !== "graw") {
      const key = `npm:${pkg.name}@${pkg.version}`;
      const repository =
        typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
      entries.set(key, {
        ecosystem: "npm",
        name: pkg.name,
        version: pkg.version,
        license:
          typeof pkg.license === "string"
            ? pkg.license
            : pkg.license?.type || "UNKNOWN",
        homepage: pkg.homepage || repository || "",
      });
    }
  } catch {
    // Ignore malformed third-party package manifests.
  }
  scanNodeModules(join(directory, "node_modules"));
}

scanNodeModules(join(root, "node_modules"));

const components = [...entries.values()].sort(
  (a, b) =>
    a.ecosystem.localeCompare(b.ecosystem) ||
    a.name.localeCompare(b.name) ||
    a.version.localeCompare(b.version),
);
const output = `// Generated by scripts/generate-licenses.mjs. Do not edit manually.
export interface ThirdPartyComponent {
  ecosystem: "Cargo" | "npm";
  name: string;
  version: string;
  license: string;
  homepage: string;
}

export const THIRD_PARTY_COMPONENTS: ThirdPartyComponent[] = ${JSON.stringify(components, null, 2)};
`;
const destination = join(root, "src", "generated", "licenses.ts");
mkdirSync(dirname(destination), { recursive: true });
writeFileSync(destination, output, "utf8");
console.log(`Generated ${components.length} third-party component records.`);
